-- V006 - Application-owned file manifest (SPEC 12).
-- Complements Spring Batch metadata; does not replace the JobRepository.
-- Deterministic identity: (business_date, checksum_sha256) is unique (SPEC 12, 39).
-- `BY DEFAULT AS IDENTITY` allows explicit NULL id on insert from Spring Data JDBC.
SET search_path TO control;

CREATE TABLE batch_file_manifest (

	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	business_date DATE NOT NULL,
	file_name VARCHAR(512) NOT NULL,
	file_uri VARCHAR(2048) NOT NULL,
	file_size_bytes BIGINT NOT NULL CHECK (file_size_bytes > 0),
	checksum_sha256 CHAR(64) NOT NULL,
	status VARCHAR(32) NOT NULL CHECK (status IN (
		'DISCOVERED',
		'VALIDATING',
		'READY',
		'PROCESSING',
		'COMPLETED',
		'FAILED',
		'QUARANTINED'
	)),
	discovered_at TIMESTAMPTZ NOT NULL,
	processing_started_at TIMESTAMPTZ,
	processing_finished_at TIMESTAMPTZ,
	record_count BIGINT,
	created_at TIMESTAMPTZ NOT NULL,
	updated_at TIMESTAMPTZ NOT NULL,

	CONSTRAINT uq_manifest_identity UNIQUE (business_date, checksum_sha256)
);

-- Operational query: monthly/weekly run lifecycle inspection (SPEC 12, 73).
CREATE INDEX idx_manifest_business_date_status ON batch_file_manifest (business_date, status);
