-- V007 - Business-facing run summary (SPEC 27, 40).
-- One row per reconciled weekly run; counters must satisfy the reconciliation
-- equation before the row is finalized as COMPLETED.
SET search_path TO control;

CREATE TABLE batch_run_summary (

	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	run_id VARCHAR(64) NOT NULL,
	business_date DATE NOT NULL,
	file_checksum CHAR(64) NOT NULL,
	read_count BIGINT NOT NULL DEFAULT 0,
	accepted_count BIGINT NOT NULL DEFAULT 0,
	rejected_count BIGINT NOT NULL DEFAULT 0,
	invalid_count BIGINT NOT NULL DEFAULT 0,
	skipped_count BIGINT NOT NULL DEFAULT 0,
	started_at TIMESTAMPTZ NOT NULL,
	finished_at TIMESTAMPTZ,
	duration_ms BIGINT,
	status VARCHAR(32) NOT NULL CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED')),
	created_at TIMESTAMPTZ NOT NULL,
	updated_at TIMESTAMPTZ NOT NULL,

	CONSTRAINT uq_run_identity UNIQUE (business_date, file_checksum),
	CONSTRAINT uq_run_id UNIQUE (run_id)
);
