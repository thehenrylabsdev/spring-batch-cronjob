-- Distributed CSV processing control plane.  Spring Batch and Quartz metadata remain
-- framework-owned; these rows are the durable worker queue, leases and checkpoints.
SET search_path TO control;

ALTER TABLE batch_file_manifest DROP CONSTRAINT IF EXISTS batch_file_manifest_status_check;
ALTER TABLE batch_file_manifest ADD CONSTRAINT batch_file_manifest_status_check CHECK (status IN
  ('DISCOVERED','VALIDATING','INDEXING','READY','PROCESSING','COMPLETED','FAILED','QUARANTINED'));
ALTER TABLE batch_file_manifest ADD COLUMN IF NOT EXISTS logical_name VARCHAR(512);
ALTER TABLE batch_file_manifest ADD COLUMN IF NOT EXISTS file_generation VARCHAR(128);
ALTER TABLE batch_file_manifest ADD COLUMN IF NOT EXISTS header_hash VARCHAR(64);
ALTER TABLE batch_file_manifest ADD COLUMN IF NOT EXISTS expected_record_count BIGINT;
ALTER TABLE batch_file_manifest ADD COLUMN IF NOT EXISTS index_started_at TIMESTAMPTZ;
ALTER TABLE batch_file_manifest ADD COLUMN IF NOT EXISTS index_finished_at TIMESTAMPTZ;
ALTER TABLE batch_file_manifest ADD COLUMN IF NOT EXISTS active_worker_count_at_plan INTEGER;
ALTER TABLE batch_file_manifest ADD COLUMN IF NOT EXISTS active_worker_slots_at_plan INTEGER;
CREATE UNIQUE INDEX IF NOT EXISTS uq_manifest_logical_sha ON batch_file_manifest (COALESCE(logical_name, file_name), checksum_sha256);

CREATE TABLE batch_worker (
  worker_id VARCHAR(128) PRIMARY KEY,
  pod_name VARCHAR(255), pod_namespace VARCHAR(255), application_version VARCHAR(128),
  status VARCHAR(16) NOT NULL CHECK (status IN ('STARTING','IDLE','BUSY','DRAINING','STOPPED')),
  worker_slots INTEGER NOT NULL CHECK (worker_slots > 0),
  started_at TIMESTAMPTZ NOT NULL, last_heartbeat_at TIMESTAMPTZ NOT NULL,
  current_job_execution BIGINT, current_partition_id BIGINT,
  shutdown_requested BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_batch_worker_active ON batch_worker(status, last_heartbeat_at);
CREATE INDEX idx_batch_worker_execution ON batch_worker(current_job_execution);

CREATE TABLE batch_partition (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  manifest_id BIGINT NOT NULL REFERENCES batch_file_manifest(id),
  job_execution_id BIGINT NOT NULL, step_execution_id BIGINT,
  step_name VARCHAR(128) NOT NULL DEFAULT 'processCsv.worker', partition_no INTEGER NOT NULL,
  start_byte BIGINT NOT NULL, end_byte_exclusive BIGINT NOT NULL,
  start_record_no BIGINT NOT NULL, end_record_no_exclusive BIGINT NOT NULL,
  expected_record_count BIGINT NOT NULL,
  status VARCHAR(16) NOT NULL CHECK (status IN ('READY','CLAIMED','RUNNING','COMPLETED','FAILED','RETRYABLE','CANCELLED')),
  worker_id VARCHAR(128), lease_version BIGINT NOT NULL DEFAULT 0, lease_expires_at TIMESTAMPTZ,
  checkpoint_byte BIGINT NOT NULL, checkpoint_record_no BIGINT NOT NULL,
  committed_read_count BIGINT NOT NULL DEFAULT 0, committed_processed_count BIGINT NOT NULL DEFAULT 0,
  accepted_count BIGINT NOT NULL DEFAULT 0, rejected_count BIGINT NOT NULL DEFAULT 0, invalid_count BIGINT NOT NULL DEFAULT 0,
  attempt_count INTEGER NOT NULL DEFAULT 0, last_error_code VARCHAR(128), last_error_message VARCHAR(2048),
  claimed_at TIMESTAMPTZ, completed_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
  CONSTRAINT uq_batch_partition_manifest_number UNIQUE (manifest_id, partition_no),
  CONSTRAINT ck_batch_partition_bytes CHECK (start_byte <= end_byte_exclusive),
  CONSTRAINT ck_batch_partition_records CHECK (start_record_no <= end_record_no_exclusive)
);
CREATE INDEX idx_batch_partition_execution_state ON batch_partition(job_execution_id, status, partition_no);
CREATE INDEX idx_batch_partition_lease ON batch_partition(status, lease_expires_at);
CREATE INDEX idx_batch_partition_worker_state ON batch_partition(worker_id, status);

ALTER TABLE batch_run_summary ADD COLUMN IF NOT EXISTS job_execution_id BIGINT;
ALTER TABLE batch_run_summary ADD COLUMN IF NOT EXISTS manifest_id BIGINT;
ALTER TABLE batch_run_summary ADD COLUMN IF NOT EXISTS active_workers_at_start INTEGER;
ALTER TABLE batch_run_summary ADD COLUMN IF NOT EXISTS maximum_workers_observed INTEGER;
ALTER TABLE batch_run_summary ADD COLUMN IF NOT EXISTS partition_count INTEGER;
ALTER TABLE batch_run_summary ADD COLUMN IF NOT EXISTS retry_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE batch_run_summary ADD COLUMN IF NOT EXISTS lease_expiration_count INTEGER NOT NULL DEFAULT 0;
